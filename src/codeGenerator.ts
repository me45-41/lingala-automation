/**
 * Code Generator pour LingalaAutomation
 * Convertit l'AST en JavaScript exécutable
 */

import { ASTNode, NodeType } from "./parser.js";
import { ObfuscateurJS } from "./obfuscateur.js";

export class CodeGenerator {
  private indent: number = 0;
  private obfuscateur: ObfuscateurJS;
  private obfusquer: boolean = false;
  private niveauObfuscation: "basique" | "moyen" | "eleve" | "extreme" = "moyen";

  constructor(options: {
    obfusquer?: boolean;
    niveauObfuscation?: "basique" | "moyen" | "eleve" | "extreme";
  } = {}) {
    this.obfuscateur = new ObfuscateurJS();
    this.obfusquer = options.obfusquer || false;
    this.niveauObfuscation = options.niveauObfuscation || "moyen";
  }

  generate(node: ASTNode): string {
    switch (node.type) {
      case NodeType.Program:
        return this.generateProgram(node);
      case NodeType.VariableDeclaration:
        return this.generateVariableDeclaration(node);
      case NodeType.FunctionDeclaration:
        return this.generateFunctionDeclaration(node);
      case NodeType.ClassDeclaration:
        return this.generateClassDeclaration(node);
      case NodeType.IfStatement:
        return this.generateIfStatement(node);
      case NodeType.WhileStatement:
        return this.generateWhileStatement(node);
      case NodeType.ReturnStatement:
        return this.generateReturnStatement(node);
      case NodeType.ExpressionStatement:
        return this.generateExpressionStatement(node);
      case NodeType.BinaryExpression:
        return this.generateBinaryExpression(node);
      case NodeType.CallExpression:
        return this.generateCallExpression(node);
      case NodeType.Literal:
        return this.generateLiteral(node);
      case NodeType.Identifier:
        return this.generateIdentifier(node);
      case NodeType.Block:
        return this.generateBlock(node);
      case NodeType.ArrayExpression:
        return this.generateArrayExpression(node);
      case NodeType.ObjectExpression:
        return this.generateObjectExpression(node);
      case NodeType.PropertyAccess:
        return this.generatePropertyAccess(node);
      default:
        throw new Error(`Unknown node type: ${node.type}`);
    }
  }

  private generateProgram(node: ASTNode): string {
    let output = "// Generated by LingalaAutomation Code Generator\n";
    output += "(async () => {\n";
    this.indent++;

    const body = Array.isArray(node.body) ? node.body : [node.body];
    for (const statement of body) {
      output += this.generate(statement);
    }

    this.indent--;
    output += "})();\n";

    // Appliquer l'obfuscation si activée
    if (this.obfusquer) {
      output = this.obfuscateur.obfusquerNiveau(output, this.niveauObfuscation);
    }

    return output;
  }

  /**
   * Active l'obfuscation du code généré
   */
  activerObfuscation(niveau: "basique" | "moyen" | "eleve" | "extreme" = "moyen"): void {
    this.obfusquer = true;
    this.niveauObfuscation = niveau;
  }

  /**
   * Désactive l'obfuscation du code généré
   */
  desactiverObfuscation(): void {
    this.obfusquer = false;
  }

  private generateVariableDeclaration(node: ASTNode): string {
    // Si le nom est "tanga", c'est une erreur de parsing - générer une assignation directe
    if (node.name === "tanga") {
      const value = this.generate(node.value);
      // Nettoyer les parenthèses
      let cleanValue = value;
      // Garde : éviter de slice sur des chaînes vides ou trop courtes
      while (cleanValue.length >= 2 && cleanValue.startsWith("(") && cleanValue.endsWith(")")) {
        cleanValue = cleanValue.slice(1, -1);
      }
      // Si la valeur contient =, extraire la partie droite
      if (cleanValue.includes("=")) {
        const parts = cleanValue.split("=");
        if (parts.length >= 2) {
          cleanValue = parts.slice(1).join("=").trim();
        }
      }
      // Nettoyer à nouveau avec garde
      while (cleanValue.length >= 2 && cleanValue.startsWith("(") && cleanValue.endsWith(")")) {
        cleanValue = cleanValue.slice(1, -1);
      }
      // Garde : éviter de générer du code vide
      if (!cleanValue) {
        cleanValue = "null";
      }
      return `${this.getIndent()}${cleanValue};\n`;
    }

    let value = this.generate(node.value);

    // Nettoyer les parenthèses inutiles avec garde
    while (value.length >= 2 && value.startsWith("(") && value.endsWith(")")) {
      value = value.slice(1, -1);
    }

    // Si la valeur contient encore un signe = (mal parsé), extraire la partie droite
    if (value.includes("=")) {
      const parts = value.split("=");
      if (parts.length >= 2) {
        value = parts.slice(1).join("=").trim();
      }
    }

    // Nettoyer à nouveau les parenthèses après extraction avec garde
    while (value.length >= 2 && value.startsWith("(") && value.endsWith(")")) {
      value = value.slice(1, -1);
    }

    // Garde : éviter de générer du code vide
    if (!value) {
      value = "null";
    }

    return `${this.getIndent()}let ${node.name} = ${value};\n`;
  }

  private generateFunctionDeclaration(node: ASTNode): string {
    const params = node.params ? node.params.join(", ") : "";
    let output = `${this.getIndent()}async function ${node.name}(${params}) {\n`;
    this.indent++;

    const body = Array.isArray(node.body) ? node.body : [node.body];
    for (const statement of body) {
      output += this.generate(statement);
    }

    this.indent--;
    output += `${this.getIndent()}}\n`;
    return output;
  }

  private generateClassDeclaration(node: ASTNode): string {
    let output = `${this.getIndent()}class ${node.name} {\n`;
    this.indent++;

    const body = Array.isArray(node.body) ? node.body : [node.body];
    for (const statement of body) {
      output += this.generate(statement);
    }

    this.indent--;
    output += `${this.getIndent()}}\n`;
    return output;
  }

  private generateIfStatement(node: ASTNode): string {
    let output = `${this.getIndent()}if (${this.generate(node.condition)}) {\n`;
    this.indent++;
    const thenBranch = Array.isArray(node.thenBranch) ? node.thenBranch : [node.thenBranch];
    for (const stmt of thenBranch) {
      output += this.generate(stmt);
    }
    this.indent--;
    output += `${this.getIndent()}}\n`;
    return output;
  }

  private generateWhileStatement(node: ASTNode): string {
    let output = `${this.getIndent()}while (${this.generate(node.condition)}) {\n`;
    this.indent++;
    const body = Array.isArray(node.body) ? node.body : [node.body];
    for (const stmt of body) {
      output += this.generate(stmt);
    }
    this.indent--;
    output += `${this.getIndent()}}\n`;
    return output;
  }

  private generateReturnStatement(node: ASTNode): string {
    if (node.value) {
      return `${this.getIndent()}return ${this.generate(node.value)};\n`;
    }
    return `${this.getIndent()}return;\n`;
  }

  private generateExpressionStatement(node: ASTNode): string {
    const expr = this.generate(node.expression);

    // Nettoyer les parenthèses inutiles pour les assignations
    let cleanExpr = expr;
    while (cleanExpr.length >= 2 && cleanExpr.startsWith("(") && cleanExpr.endsWith(")")) {
      cleanExpr = cleanExpr.slice(1, -1);
    }

    return `${this.getIndent()}${cleanExpr};\n`;
  }

  private generateBinaryExpression(node: ASTNode): string {
    // Cas spécial pour l'opérateur NOT (!)
    if (node.operator === "!") {
      return `(!${this.generate(node.right)})`;
    }
    return `(${this.generate(node.left)} ${node.operator} ${this.generate(node.right)})`;
  }

  private generateCallExpression(node: ASTNode): string {
    const args = node.arguments ? node.arguments.map((arg: ASTNode) => this.generate(arg)).join(", ") : "";
    const callee = this.generate(node.callee);

    // Pour l'instantiation de classe
    if (node.callee && node.callee.type === NodeType.Identifier &&
        this.isClassName(node.callee.name)) {
      return `new ${callee}(${args})`;
    }

    // Pour elobi -> console.log
    if (node.callee && node.callee.type === NodeType.Identifier &&
        node.callee.name === "elobi") {
      return `console.log(${args})`;
    }

    return `${callee}(${args})`;
  }

  private generateLiteral(node: ASTNode): string {
    if (typeof node.value === 'string') {
      return `"${node.value}"`;
    }
    return String(node.value);
  }

  private generateIdentifier(node: ASTNode): string {
    return node.name;
  }

  private generateBlock(statements: ASTNode | ASTNode[]): string {
    let output = '';
    const stmts = Array.isArray(statements) ? statements : [statements];
    for (const statement of stmts) {
      // Ignorer les statements null (ex: susa)
      if (statement && !(statement.type === NodeType.Literal && statement.value === null)) {
        output += this.generate(statement);
      }
    }
    return output;
  }

  private generateArrayExpression(node: ASTNode): string {
    const elements = node.elements ? node.elements.map((el: ASTNode) => this.generate(el)).join(", ") : "";
    return `[${elements}]`;
  }

  private generateObjectExpression(node: ASTNode): string {
    if (!node.properties) return "{}";
    const props = Array.from(node.properties.entries())
      .map(([key, value]) => `"${key}": ${this.generate(value)}`)
      .join(", ");
    return `{${props}}`;
  }

  private generatePropertyAccess(node: ASTNode): string {
    return `${this.generate(node.object)}.${node.property}`;
  }

  private getIndent(): string {
    return '  '.repeat(this.indent);
  }

  private isClassName(name: string): boolean {
    // Liste des noms de classes connus (peut être étendu)
    const classNames = ['Muntu', 'Etudiant', 'Personne', 'Animal'];
    return classNames.includes(name);
  }
}
